"""Rebuild the portable browser traces from the same simulators used by the CLI."""

import argparse
import json
from pathlib import Path
import sys

from bench import trace

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from lab import simulate, summarize


def make_traces():
    result = {}
    for state in ("zero", "one", "plus", "minus", "plus-i", "minus-i"):
        result[state] = {}
        for receiver in ("broken", "ideal"):
            rows = []
            for bits in ("00", "01", "10", "11"):
                row = trace(state, bits, receiver, "day")
                rows.append({key: row[key] for key in (
                    "bits", "branch_probability", "gates", "basis", "expected_bit",
                    "readout_probabilities", "pass_probability"
                )})
            result[state][receiver] = rows
    calibration = summarize(simulate("entangled", 4096, 7))
    return {"bellScore": calibration["s"], "traces": result}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="detect stale browser data")
    check = parser.parse_args().check
    dest = HERE / "trace-data.js"
    data = json.dumps(make_traces(), separators=(",", ":"), allow_nan=False)
    content = "// Generated by export_web.py.\nwindow.LINK_BENCH = " + data + ";\n"
    if check:
        if not dest.exists() or dest.read_text() != content:
            raise SystemExit("Browser traces are stale. Run python3 teleport/export_web.py.")
    else:
        dest.write_text(content)
