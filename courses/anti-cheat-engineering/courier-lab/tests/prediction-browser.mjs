import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { withServer } from './harness.mjs';

const output = fileURLToPath(new URL('../../../../dist/anti-cheat-browser/prediction/', import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const results = [];
try {
  await withServer(async server => {
    for (const width of [1280, 390, 320]) {
      const context = await browser.newContext({ viewport: { width, height: 900 } });
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(server.base + '/completion');
      await page.locator('#show-timing-answer').waitFor();
      assert.equal(await page.locator('#timing-checkpoints').textContent(), '');
      assert.equal(await page.locator('#recovery-state').textContent(), '');
      assert.equal(await page.locator('#repair-state').textContent(), '');
      assert.equal(await page.locator('#timing-input').textContent().then(text => text.includes('first-owner-tick')), false);
      await page.selectOption('#timing-case', '6');
      await page.click('#show-timing');
      assert.equal(await page.locator('#timing-checkpoints').textContent(), '');
      assert.match(await page.locator('#timing').innerText(), /Write a prediction/);
      await page.locator('#show-timing-answer').fill('I think the pause advances every nominal tick.');
      await page.locator('#show-timing').focus();
      await page.keyboard.press('Enter');
      const checkpoints = JSON.parse(await page.locator('#timing-checkpoints').textContent());
      assert.equal(checkpoints[2].clock.dropped, 11);
      assert.equal(checkpoints.at(-1).tick, 6);
      await page.locator('#show-timing').scrollIntoViewIfNeeded();
      await page.screenshot({ path: `${output}/${width}-notebook-viewport.png` });
      await page.locator('#show-timing-answer').fill('Revision: catch-up is bounded; the leftover fraction stays.');
      await page.click('#show-timing');
      let events = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('courier-predictions-v1:')).map(key => JSON.parse(localStorage[key])));
      const answers = events.filter(event => event.kind === 'answer').sort((a, b) => a.sequence - b.sequence);
      assert.equal(answers.length, 2);
      assert.equal(answers[0].answer, 'I think the pause advances every nominal tick.');
      assert.equal(answers[0].priorExposure, false);
      assert.equal(answers[1].priorExposure, true);
      assert.match(answers[0].case.question, /Predict the processed tick/);
      assert.equal(answers[0].case.inputs.actions[0].label, 'step-1');
      await page.reload();
      await page.locator('#show-timing-answer').waitFor();
      await page.selectOption('#timing-case', '6');
      assert.match(await page.locator('#timing').innerText(), /already been viewed/);
      assert.match(await page.locator('#show-timing-answer').inputValue(), /Revision/);
      await page.click('#show-repair-worked');
      assert.match(await page.locator('#repair-result').textContent(), /repaired/);
      events = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('courier-predictions-v1:')).map(key => JSON.parse(localStorage[key])));
      assert.equal(events.filter(event => event.case.id === 'capstone/request-1' && event.kind === 'answer').length, 0);
      assert.equal(events.find(event => event.case.id === 'capstone/request-1').mode, 'worked-example');
      await page.screenshot({ path: `${output}/${width}-completion.png`, fullPage: true });
      await page.goto(server.base + '/analysis');
      await page.locator('#show-evaluation-answer').waitFor();
      assert.equal(await page.locator('#evaluation-results').isVisible(), false);
      assert.equal(await page.locator('#retention-results').isVisible(), false);
      assert.doesNotMatch(await page.locator('body').innerText(), /8-tick window misses/);
      await page.locator('#show-evaluation-answer').fill('I predict one positive; I will count each case once.');
      await page.click('#show-evaluation');
      assert.equal(await page.locator('#evaluation-results').isVisible(), true);
      await page.screenshot({ path: `${output}/${width}-analysis.png`, fullPage: true });
      await page.goto(server.base + '/evidence');
      await page.locator('#compare-package-answer').waitFor();
      assert.equal(await page.locator('#package-feedback').isVisible(), false);
      assert.equal(await page.locator('#replay-arena').isVisible(), false);
      await page.click('#replay-trace-worked');
      assert.equal(await page.locator('#replay-arena').isVisible(), true);
      for (let index = 0; index < 3; index += 1) await page.click('#step-trace');
      assert.equal(await page.locator('#replay-actor').getAttribute('cx'), '1250');
      await page.click('#back-trace');
      assert.equal(await page.locator('#replay-actor').getAttribute('cx'), '1000');
      assert.match(await page.locator('#trace-step').textContent(), /Recorded event 2/);
      await page.click('#step-trace');
      assert.equal(await page.locator('#replay-actor').getAttribute('cx'), '1250');
      await page.selectOption('#trace-case', 'missing');
      assert.equal(await page.locator('#replay-arena').isVisible(), false);
      await page.click('#replay-trace-worked');
      assert.match(await page.locator('#trace-verdict').textContent(), /sequence/);
      assert.equal(await page.locator('#replay-arena').isVisible(), false);
      assert.match(await page.locator('#trace-step').textContent(), /No replay state/);
      assert.equal(await page.locator('#step-trace').isDisabled(), true);
      assert.equal(await page.locator('#back-trace').isDisabled(), true);
      await page.screenshot({ path: `${output}/${width}-evidence.png`, fullPage: true });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width);
      assert.deepEqual(errors, []);
      results.push({ width, firstPreserved: true, revisionAssisted: true, reload: true, workedAssistance: true, noInitialResult: true, staleReplayCleared: true, errors });
      await context.close();
    }
    const context = await browser.newContext();
    const page = await context.newPage();
    await page.addInitScript(() => { Storage.prototype.setItem = function () { throw new DOMException('Quota full', 'QuotaExceededError'); }; });
    await page.goto(server.base + '/completion');
    await page.locator('#show-timing-answer').fill('Must remain hidden.');
    await page.click('#show-timing');
    assert.equal(await page.locator('#timing-checkpoints').textContent(), '');
    assert.match(await page.locator('#timing').innerText(), /Not saved — results remain hidden/);
    await page.click('#show-repair-worked');
    assert.equal(await page.locator('#repair-state').textContent(), '');
    await page.locator('a[href="/course"]').first().click();
    assert.equal(new URL(page.url()).pathname, '/course');
    await context.close();
    results.push({ storageFailureBlocksBothRevealPaths: true, navigationOpen: true });
  });
} finally { await browser.close(); }
await writeFile(`${output}/results.json`, JSON.stringify(results, null, 2) + '\n');
console.log(JSON.stringify(results, null, 2));
