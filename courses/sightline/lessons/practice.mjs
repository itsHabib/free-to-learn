// Practice items for the Sightline lessons, keyed by the {{practice:ID}} markers in
// lessons/NN.md. Same shape as the example course's practice.mjs:
//   q(objective, prompt, answer, feedback, wrong, section)
//   objective: the lesson whose objective the item tests ('01' to '08'); the pointer
//              after a miss names lesson <objective> and <section>.
//   answer:    a number, a yes/no boolean, a list of numbers, or one word.
//   feedback:  the reason shown for the right answer and for any wrong answer not in `wrong`.
//   wrong:     [{ answer, feedback }] for the most likely wrong answers.
//   section:   the exact '## ' heading in lessons/<objective>.md that teaches the item.
// anyOrder(item) marks a list answer whose order carries no meaning.
// { ...q(...), round: true } marks a whole-number answer for which a more precise number
// that rounds to it also counts (656.06 for 656). Without it a whole number must be exact.
// Ids starting with p and a digit are predictions; the rest are practice. Every id has
// at least two items, the second a fresh case on the same idea. Every number here is
// derived in lessons/NUMBERS.md.
